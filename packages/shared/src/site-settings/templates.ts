/** テンプレート内の {{key}} を置き換える */
export function renderTemplate(
  template: string,
  values: Record<string, string>
): string {
  return template.replace(/\{\{\s*([a-z_]+)\s*\}\}/g, (match, key: string) =>
    key in values ? values[key] : match
  );
}
